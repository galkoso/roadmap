import { expect, test } from '@playwright/test';
test('team heading is date-free, stays visible on both pages and contains scheduled and backlog tasks', async ({ page }) => {
  await page.goto('/backlog'); await expect(page.locator('.save-state')).toHaveText('נשמר');
  await page.getByRole('button', { name: 'כותרת חדשה' }).click();
  const headingDialog = page.getByRole('dialog', { name: 'כותרת חדשה', exact: true });
  await expect(headingDialog.locator('input[type=number], input[type=date]')).toHaveCount(0);
  await headingDialog.getByLabel('שם הכותרת').fill('כותרת צוות לבדיקה');
  await headingDialog.getByLabel('צוות הכותרת').selectOption('team-b');
  await headingDialog.getByRole('button', { name: 'שמירת כותרת', exact: true }).click();
  const group = page.locator('.backlog-work-group').filter({ hasText: 'כותרת צוות לבדיקה' });
  await expect(group).toHaveCount(1);
  await expect(group.locator('xpath=ancestor::section[@data-group][1]')).toHaveAttribute('data-group', 'team:team-b');
  await group.getByRole('button', { name: 'הוספת משימה תחת כותרת צוות לבדיקה' }).click();
  const taskDialog = page.getByRole('dialog', { name: 'פריט לבקלוג', exact: true });
  await expect(taskDialog.getByLabel('צוות', { exact: true })).toHaveValue('team-b');
  await expect(taskDialog.getByLabel('כותרת', { exact: true })).not.toHaveValue('');
  await taskDialog.getByLabel('כותרת הפריט').fill('משימה בבקלוג תחת כותרת');
  await taskDialog.getByRole('button', { name: 'שמירת פריט', exact: true }).click();
  await expect(group.locator('.backlog-row')).toHaveCount(1);
  await expect(group.locator('.backlog-scope')).toContainText('5 ימי עבודה');
  await expect(page.locator('.save-state')).toHaveText('נשמר'); await page.reload();
  await expect(group.locator('.backlog-row')).toHaveCount(1);
  await page.getByRole('link', { name: 'Roadmap', exact: true }).click();
  const roadmapHeading = page.locator('.timeline-row.work-row').filter({ hasText: 'כותרת צוות לבדיקה' });
  await expect(roadmapHeading).toHaveCount(1); await expect(roadmapHeading.locator('.bar')).toHaveCount(0);
  await roadmapHeading.getByRole('button', { name: 'הוספת משימה תחת כותרת צוות לבדיקה', exact: true }).click();
  const editor = page.getByRole('region', { name: 'עריכת משימה', exact: true });
  await expect(editor.getByLabel('צוות אחראי')).toHaveValue('team-b');
  await editor.getByLabel('שם המשימה').fill('משימה מתוזמנת תחת כותרת');
  await editor.getByRole('button', { name: 'הוספת משימה', exact: true }).click();
  await expect(page.locator('.task-name').filter({ hasText: 'משימה מתוזמנת תחת כותרת' })).toBeVisible();
  await expect(roadmapHeading.locator('.bar')).toHaveCount(0);
  await expect(page.locator('.save-state')).toHaveText('נשמר');
  await page.screenshot({ path: 'test-results/headings-roadmap.png', fullPage: true });
  await page.getByRole('link', { name: 'בקלוג', exact: true }).click();
  await expect(group.locator('.backlog-row')).toHaveCount(1);
  await group.getByRole('button', { name: 'שיבוץ בזמן' }).click();
  await page.getByRole('dialog', { name: 'שיבוץ בזמן', exact: true }).getByRole('button', { name: 'אישור שיבוץ', exact: true }).click();
  await expect(group.locator('.backlog-row')).toHaveCount(0); await expect(group).toBeVisible();
  await page.screenshot({ path: 'test-results/headings-backlog.png', fullPage: true });
});
test('roadmap creation separates headings from tasks and filters headings by team', async ({ page }) => {
  await page.goto('/roadmap'); await expect(page.locator('.save-state')).toHaveText('נשמר');
  await page.getByRole('button', { name: 'כותרת חדשה' }).click();
  const dialog = page.getByRole('dialog', { name: 'כותרת חדשה', exact: true });
  await dialog.getByLabel('שם הכותרת').fill('קבוצת צוות א');
  await dialog.getByRole('button', { name: 'שמירת כותרת', exact: true }).click();
  const heading = page.locator('.timeline-row.work-row').filter({ hasText: 'קבוצת צוות א' });
  await expect(heading).toBeVisible(); await expect(heading.locator('.bar')).toHaveCount(0);
  await page.getByRole('button', { name: 'משימה חדשה', exact: false }).click();
  const editor = page.getByRole('region', { name: 'עריכת משימה', exact: true });
  await editor.getByLabel('שם המשימה').fill('משימה עצמאית');
  await editor.getByLabel('צוות אחראי').selectOption('team-b');
  await expect(editor.getByLabel('כותרת', { exact: true }).getByRole('option', { name: 'קבוצת צוות א' })).toHaveCount(0);
  await editor.getByLabel('צוות אחראי').selectOption('team-a');
  await editor.getByLabel('כותרת', { exact: true }).selectOption({ label: 'קבוצת צוות א' });
  await editor.getByRole('button', { name: 'הוספת משימה', exact: true }).click();
  await expect(page.locator('.task-name').filter({ hasText: 'משימה עצמאית' })).toBeVisible();
  await heading.getByRole('button', { name: 'עריכת כותרת', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'עריכת כותרת', exact: true });
  await edit.getByLabel('שם הכותרת').fill('שם כותרת מעודכן');
  await edit.getByRole('button', { name: 'שמירת כותרת', exact: true }).click();
  await page.getByRole('link', { name: 'בקלוג', exact: true }).click();
  const backlogHeading = page.locator('.backlog-work-group').filter({ hasText: 'שם כותרת מעודכן' });
  await expect(backlogHeading).toBeVisible();
  await backlogHeading.getByRole('button', { name: 'עריכת כותרת שם כותרת מעודכן' }).click();
  page.once('dialog', prompt => prompt.accept());
  await page.getByRole('dialog', { name: 'עריכת כותרת', exact: true }).getByRole('button', { name: 'מחיקת כותרת', exact: true }).click();
  await expect(backlogHeading).toHaveCount(0);
  await page.getByRole('heading', { level: 1 }).click(); await page.keyboard.press('Control+z');
  await expect(backlogHeading).toBeVisible();
  await expect(page.locator('.save-state')).toHaveText('נשמר');
});
